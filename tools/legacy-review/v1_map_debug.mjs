import { chromium } from 'playwright';
import path from 'node:path';
const W = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const browser = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs=[]; page.on('console', m => logs.push(m.type()+': '+m.text())); page.on('pageerror', e => logs.push('PAGEERROR: '+e.message));
await page.goto('file://' + path.join(W, 'ref/v1.html') + '?test&speed=4');
await page.waitForFunction(() => !!window.__ali, null, { timeout: 120000 });
await page.waitForTimeout(2000);
await page.evaluate(() => window.__ali.game.start());
await page.waitForFunction(() => window.__ali.state().location.type === 'station' && !window.__ali.state().busy, null, { timeout: 120000 });
await page.waitForTimeout(1000);
const r = await page.evaluate(() => { const g = window.__ali.game; const before = !!g.hud.modalOpen; g.openMap(); return { before, after: !!g.hud.modalOpen, busy: g.busy, mapUrlLen: g.mapImage?.url?.length ?? null, extent: g.mapImage?.extent }; });
console.log(JSON.stringify(r));
await page.waitForTimeout(1500); await page.evaluate(() => document.getAnimations().forEach(a => a.finish())); await page.waitForTimeout(1500);
const st = await page.evaluate(() => { const m = document.querySelector('.modal'); if (!m) return 'no modal'; const c = m.querySelector('.modal-card'); return { modalOpacity: getComputedStyle(m).opacity, cardOpacity: getComputedStyle(c).opacity, anim: m.getAnimations().map(a => [a.animationName, a.playState, a.currentTime]), cardAnims: c.getAnimations().map(a => [a.animationName, a.playState, a.currentTime]), markers: m.querySelectorAll('.map-marker').length, img: !!m.querySelector('img') }; });
console.log(JSON.stringify(st));
await page.screenshot({ path: path.join(W, 'shots/v1_map.png') });
console.log(logs.join('\n'));
await browser.close();
